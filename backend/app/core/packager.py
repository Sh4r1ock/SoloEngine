def set_project_context(project_id: str, base_path: str):
    """设置项目上下文（沙箱）。"""
    global PROJECT_ID, SANDBOX_BASE_PATH, CURRENT_PROJECT
    PROJECT_ID = project_id
    SANDBOX_BASE_PATH = base_path
    CURRENT_PROJECT = {{"id": project_id, "path": base_path}}
    logger.info(f"Project context set: {{project_id}}, base_path={{base_path}}")


def get_sandboxed_path(relative_path: str) -> str:
    """获取沙箱内的安全路径。"""
    if not SANDBOX_BASE_PATH:
        raise ValueError("No project selected. Please set project context first.")
    
    relative_path = relative_path.lstrip("/\\\\")
    absolute_path = os.path.abspath(os.path.join(SANDBOX_BASE_PATH, relative_path))
    
    if not absolute_path.startswith(SANDBOX_BASE_PATH):
        raise PermissionError(f"Access denied: path '{{relative_path}}' is outside the sandbox")
    
    return absolute_path


@dataclass
class NodeResult:
    """节点执行结果。"""
    node_id: str
    status: str
    output: Optional[Dict[str, Any]] = None
    error: Optional[str] = None
    started_at: Optional[str] = None
    completed_at: Optional[str] = None


class AgentRunner:
    """Agent runner for packaged flow."""

    def __init__(self):
        self.nodes: Dict[str, Dict[str, Any]] = {{}}
        self.edges: List[Dict[str, Any]] = []
        self.execution_context: Dict[str, Any] = {{}}
        self.results: List[NodeResult] = []

    async def initialize(self):
        """Initialize the flow."""
        self.nodes = {{n["id"]: n for n in FLOW_CONFIG.get("nodes", [])}}
        self.edges = FLOW_CONFIG.get("edges", [])
        logger.info(f"Initialized flow with {{len(self.nodes)}} nodes and {{len(self.edges)}} edges")

    def _get_entry_nodes(self) -> List[str]:
        """获取入口节点（没有入边的节点）。"""
        target_nodes = {{e["target"] for e in self.edges}}
        return [nid for nid in self.nodes.keys() if nid not in target_nodes]

    def _get_next_nodes(self, node_id: str) -> List[str]:
        """获取下一个要执行的节点。"""
        return [e["target"] for e in self.edges if e["source"] == node_id]

    async def execute_node(self, node_id: str, input_data: Dict[str, Any]) -> NodeResult:
        """执行单个节点。"""
        node = self.nodes.get(node_id)
        if not node:
            return NodeResult(
                node_id=node_id,
                status="failed",
                error=f"Node {{node_id}} not found"
            )

        started_at = datetime.now().isoformat()
        logger.info(f"Executing node: {{node_id}} ({{node.get('data', {{}}).get('agentType', 'unknown')}})")

        try:
            node_data = node.get("data", {{}})
            agent_type = node_data.get("agentType", "executor")
            
            # 根据节点类型执行不同的逻辑
            if agent_type == "orchestrator":
                output = await self._execute_orchestrator(node_id, node_data, input_data)
            elif agent_type == "planner":
                output = await self._execute_planner(node_id, node_data, input_data)
            else:
                output = await self._execute_executor(node_id, node_data, input_data)

            return NodeResult(
                node_id=node_id,
                status="completed",
                output=output,
                started_at=started_at,
                completed_at=datetime.now().isoformat()
            )
        except Exception as e:
            logger.error(f"Node {{node_id}} failed: {{e}}")
            return NodeResult(
                node_id=node_id,
                status="failed",
                error=str(e),
                started_at=started_at,
                completed_at=datetime.now().isoformat()
            )

    async def _execute_orchestrator(self, node_id: str, node_data: Dict, input_data: Dict) -> Dict[str, Any]:
        """执行协调者节点。"""
        # 协调者节点负责全局调度和决策
        return {{
            "node_id": node_id,
            "type": "orchestrator",
            "input": input_data,
            "decision": "continue",
            "context_update": {{}}
        }}

    async def _execute_planner(self, node_id: str, node_data: Dict, input_data: Dict) -> Dict[str, Any]:
        """执行规划者节点。"""
        # 规划者节点负责任务分解和规划
        return {{
            "node_id": node_id,
            "type": "planner",
            "input": input_data,
            "plan": [],
            "context_update": {{}}
        }}

    async def _execute_executor(self, node_id: str, node_data: Dict, input_data: Dict) -> Dict[str, Any]:
        """执行执行者节点。"""
        # 执行者节点负责具体任务执行
        return {{
            "node_id": node_id,
            "type": "executor",
            "input": input_data,
            "result": "executed",
            "context_update": {{}}
        }}

    async def run(self, input_data: Dict[str, Any]) -> Dict[str, Any]:
        """Run the flow."""
        entry_nodes = self._get_entry_nodes()
        
        if not entry_nodes:
            return {{
                "status": "failed",
                "error": "No entry nodes found",
                "results": []
            }}

        # 从入口节点开始执行
        for entry_node_id in entry_nodes:
            result = await self.execute_node(entry_node_id, input_data)
            self.results.append(result)
            
            if result.status == "completed":
                # 继续执行后续节点
                await self._execute_downstream(entry_node_id, result.output or {{}})

        return {{
            "status": "success" if all(r.status == "completed" for r in self.results) else "partial",
            "input": input_data,
            "nodes_count": len(self.nodes),
            "executed_count": len(self.results),
            "results": [{{"node_id": r.node_id, "status": r.status}} for r in self.results]
        }}

    async def _execute_downstream(self, node_id: str, context: Dict[str, Any]):
        """执行下游节点。"""
        next_nodes = self._get_next_nodes(node_id)
        
        for next_node_id in next_nodes:
            result = await self.execute_node(next_node_id, context)
            self.results.append(result)
            
            if result.status == "completed":
                await self._execute_downstream(next_node_id, {{**context, **(result.output or {{}})}})


