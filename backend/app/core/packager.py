    async def create_package(
        self,
        project_name: str,
        config: Optional[PackageConfig] = None,
    ) -> PackageResult:
        """创建包。"""
        # 加载流程数据
        flows_dir = self._get_flows_dir()
        flow_file = flows_dir / f"{project_name}.json"

        if not flow_file.exists():
            raise FileNotFoundError(f"Project '{project_name}' not found")

        with open(flow_file, "r", encoding="utf-8") as f:
            flow_data = json.load(f)

        # 使用默认配置或提供的配置
        if config is None:
            config = PackageConfig(
                name=project_name,
                description=f"Packaged from {project_name}",
            )

        # 创建包 ID
        package_id = str(uuid.uuid4())

        # 创建临时目录
        temp_dir = self.output_dir / f"temp_{package_id}"
        temp_dir.mkdir(parents=True, exist_ok=True)

        try:
            # 复制流程数据
            with open(temp_dir / "flow.json", "w", encoding="utf-8") as f:
                json.dump(flow_data, f, indent=2, ensure_ascii=False)

            # 生成主程序
            main_py = self._generate_main_py(flow_data, config)
            with open(temp_dir / f"{config.entry_point}.py", "w", encoding="utf-8") as f:
                f.write(main_py)

            # 生成 Dockerfile
            dockerfile = self._generate_dockerfile(config)
            with open(temp_dir / "Dockerfile", "w", encoding="utf-8") as f:
                f.write(dockerfile)

            # 生成 README
            readme = self._generate_readme(config)
            with open(temp_dir / "README.md", "w", encoding="utf-8") as f:
                f.write(readme)

            # 生成 requirements.txt
            requirements = self._generate_requirements(config.dependencies)
            with open(temp_dir / "requirements.txt", "w", encoding="utf-8") as f:
                f.write(requirements)

            # 生成 docker-compose.yml
            compose = self._generate_compose(config)
            with open(temp_dir / "docker-compose.yml", "w", encoding="utf-8") as f:
                f.write(compose)

            # 复制 Skills
            skills_dir = self._get_skills_dir()
            if skills_dir.exists():
                dest_skills = temp_dir / "skills"
                if skills_dir.exists():
                    shutil.copytree(skills_dir, dest_skills, dirs_exist_ok=True)

            # 创建 ZIP 包
            output_file = self.output_dir / f"{config.name}-{config.version}.zip"
            files_count = 0

            with zipfile.ZipFile(output_file, "w", zipfile.ZIP_DEFLATED) as zf:
                for root, dirs, files in os.walk(temp_dir):
                    for file in files:
                        file_path = Path(root) / file
                        arc_name = file_path.relative_to(temp_dir)
                        zf.write(file_path, arc_name)
                        files_count += 1

            # 获取包大小
            size_bytes = output_file.stat().st_size

            # 清理临时目录
            shutil.rmtree(temp_dir)

            logger.info(f"Created package: {output_file}")

            return PackageResult(
                package_id=package_id,
                name=config.name,
                version=config.version,
                output_path=str(output_file),
                size_bytes=size_bytes,
                created_at=datetime.now().isoformat(),
                files_count=files_count,
            )

        except Exception as e:
            # 清理临时目录
            if temp_dir.exists():
                shutil.rmtree(temp_dir)
            raise

    async def list_packages(self) -> List[Dict[str, Any]]:
        """列出所有包。"""
        packages = []

        for zip_file in self.output_dir.glob("*.zip"):
            try:
                stat = zip_file.stat()
                packages.append({
                    "name": zip_file.stem,
                    "path": str(zip_file),
                    "size_bytes": stat.st_size,
                    "created_at": datetime.fromtimestamp(stat.st_ctime).isoformat(),
                })
            except Exception as e:
                logger.error(f"Failed to read package {zip_file}: {e}")

        return sorted(packages, key=lambda x: x["created_at"], reverse=True)

    async def delete_package(self, package_name: str) -> bool:
        """删除包。"""
        package_file = self.output_dir / f"{package_name}.zip"

        if not package_file.exists():
            # 尝试匹配版本号
            matches = list(self.output_dir.glob(f"{package_name}*.zip"))
            if matches:
                package_file = matches[0]
            else:
                return False

        try:
            package_file.unlink()
            logger.info(f"Deleted package: {package_file}")
            return True
        except Exception as e:
            logger.error(f"Failed to delete package: {e}")
            return False

    async def get_package_info(self, package_name: str) -> Optional[Dict[str, Any]]:
        """获取包信息。"""
        package_file = self.output_dir / f"{package_name}.zip"

        if not package_file.exists():
            matches = list(self.output_dir.glob(f"{package_name}*.zip"))
            if matches:
                package_file = matches[0]
            else:
                return None

        try:
            stat = package_file.stat()

            with zipfile.ZipFile(package_file, "r") as zf:
                files = zf.namelist()

            return {
                "name": package_file.stem,
                "path": str(package_file),
                "size_bytes": stat.st_size,
                "created_at": datetime.fromtimestamp(stat.st_ctime).isoformat(),
                "files": files,
                "files_count": len(files),
            }
        except Exception as e:
            logger.error(f"Failed to read package info: {e}")
            return None


